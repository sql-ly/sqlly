//! Relay outer-frame codec.
//!
//! The relay outer frame is a fixed 60-byte header followed by an opaque body.
//! All multi-byte integer fields are little-endian. UUID fields are the raw 16
//! bytes in canonical (network) order, so they survive the round trip
//! byte-for-byte regardless of host endianness and match the inner
//! authenticated chunk metadata used by `sqlly-noise`.
//!
//! Header layout (offsets in bytes):
//!
//! | off | size | field                          |
//! |-----|------|--------------------------------|
//! | 0   | 4    | `frame_len` (LE)               |
//! | 4   | 2    | `protocol_version` (LE)        |
//! | 6   | 1    | `frame_kind`                   |
//! | 7   | 1    | `flags`                        |
//! | 8   | 16   | `source_client_id` (raw)       |
//! | 24  | 16   | `destination_client_id` (raw)  |
//! | 40  | 8    | `message_id` (LE)              |
//! | 48  | 4    | `chunk_index` (LE)             |
//! | 52  | 4    | `chunk_count_or_reserved` (LE) |
//! | 56  | 4    | `body_len` (LE)                |
//! | 60  | ..   | `body`                         |
//!
//! `frame_len` counts every byte that follows the `frame_len` field itself,
//! i.e. `(HEADER_LEN - 4) + body_len`. A reader can therefore read four bytes,
//! then read exactly `frame_len` more bytes to obtain one complete frame.

use bytes::{Buf, BufMut, Bytes, BytesMut};
use uuid::Uuid;

use crate::error::WireError;

/// The relay wire protocol version this build speaks. Independent of the engine
/// protocol/layout versions tunnelled inside the body.
pub const PROTOCOL_VERSION: u16 = 1;

/// Size of the fixed relay frame header, in bytes.
pub const HEADER_LEN: usize = 60;

/// Number of leading bytes occupied by the `frame_len` length prefix.
pub const FRAME_LEN_PREFIX: usize = 4;

/// Value of `frame_len` for a frame with an empty body: everything after the
/// prefix, i.e. the rest of the header.
pub const MIN_FRAME_LEN: usize = HEADER_LEN - FRAME_LEN_PREFIX;

/// Maximum permitted body length. Bodies carry a single (already chunked,
/// Noise-sealed) payload, so this is a generous but firm DoS bound.
pub const MAX_BODY_LEN: usize = 16 * 1024 * 1024;

/// Maximum permitted `frame_len` value, derived from [`MAX_BODY_LEN`].
pub const MAX_FRAME_LEN: usize = MIN_FRAME_LEN + MAX_BODY_LEN;

/// Flag bit marking the final chunk of a multi-chunk message.
pub const FLAG_LAST_CHUNK: u8 = 0b0000_0001;

/// Mask of every flag bit this build understands. Any bit outside this mask is
/// reserved and must be zero.
pub const KNOWN_FLAGS: u8 = FLAG_LAST_CHUNK;

/// Kind of a relay frame, carried in the one-byte `frame_kind` header field.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[repr(u8)]
pub enum FrameKind {
    /// Client-to-relay authentication handshake.
    Auth = 1,
    /// End-to-end Noise handshake message being forwarded between peers.
    NoiseHandshake = 2,
    /// End-to-end encrypted application data being forwarded between peers.
    Data = 3,
    /// Keepalive request.
    Ping = 4,
    /// Keepalive response.
    Pong = 5,
    /// Relay-generated error (non-authoritative transport hint).
    RelayError = 6,
    /// Graceful session close.
    Close = 7,
    /// Relay notice that a previously granted route was revoked.
    RouteRevoked = 8,
}

impl FrameKind {
    /// Map a raw `frame_kind` byte to a [`FrameKind`], or `None` if unknown.
    #[must_use]
    pub fn from_u8(v: u8) -> Option<Self> {
        Some(match v {
            1 => Self::Auth,
            2 => Self::NoiseHandshake,
            3 => Self::Data,
            4 => Self::Ping,
            5 => Self::Pong,
            6 => Self::RelayError,
            7 => Self::Close,
            8 => Self::RouteRevoked,
            _ => return None,
        })
    }

    /// The raw byte encoding of this kind.
    #[must_use]
    pub fn as_u8(self) -> u8 {
        self as u8
    }
}

/// Relay error codes carried in the body of a [`FrameKind::RelayError`] frame.
///
/// These are transport hints generated by the relay itself and are *not*
/// end-to-end authenticated; endpoints treat them as advisory.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[repr(u8)]
pub enum RelayErrorCode {
    /// The destination client is not currently connected to the relay.
    DestOffline = 1,
    /// No route grant authorizes this source/destination pair.
    RoutingDenied = 2,
    /// The client failed relay authentication.
    AuthFailed = 3,
    /// The frame violated the relay protocol (e.g. spoofed source id).
    ProtocolError = 4,
    /// The client exceeded a rate limit.
    RateLimited = 5,
    /// The relay is at capacity and cannot accept the connection.
    RelayFull = 6,
    /// The account's concurrent bridged-session allowance is exhausted (the
    /// control plane refused the session; for a shared bridge this is the
    /// bridge OWNER's allowance).
    SessionLimit = 7,
}

impl RelayErrorCode {
    /// Map a raw byte to a [`RelayErrorCode`], or `None` if unknown.
    #[must_use]
    pub fn from_u8(v: u8) -> Option<Self> {
        Some(match v {
            1 => Self::DestOffline,
            2 => Self::RoutingDenied,
            3 => Self::AuthFailed,
            4 => Self::ProtocolError,
            5 => Self::RateLimited,
            6 => Self::RelayFull,
            7 => Self::SessionLimit,
            _ => return None,
        })
    }

    /// The raw byte encoding of this code.
    #[must_use]
    pub fn as_u8(self) -> u8 {
        self as u8
    }
}

/// A decoded relay outer frame. The body is an opaque [`Bytes`] so the relay
/// can forward it without copying and without understanding its contents.
///
/// `frame_len` and `body_len` are not stored: they are derived from `body` on
/// encode and validated on decode.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RelayFrame {
    /// Relay wire protocol version.
    pub protocol_version: u16,
    /// Frame kind.
    pub kind: FrameKind,
    /// Flag bits. Only bits in [`KNOWN_FLAGS`] may be set.
    pub flags: u8,
    /// Authenticated source client id. Never nil.
    pub source: Uuid,
    /// Destination client id. Never nil.
    pub destination: Uuid,
    /// Application message id (groups chunks of one logical message).
    pub message_id: u64,
    /// Zero-based index of this chunk within the message.
    pub chunk_index: u32,
    /// Total chunk count for the message, or a reserved value for
    /// non-chunked kinds.
    pub chunk_count: u32,
    /// Opaque body bytes.
    pub body: Bytes,
}

impl RelayFrame {
    /// Construct a frame with the current [`PROTOCOL_VERSION`], no flags, and a
    /// single-chunk message shape. Callers typically use this then override the
    /// chunk fields, or use the chunk-aware constructors in `crate::chunk`.
    #[must_use]
    pub fn new(
        kind: FrameKind,
        source: Uuid,
        destination: Uuid,
        message_id: u64,
        body: Bytes,
    ) -> Self {
        Self {
            protocol_version: PROTOCOL_VERSION,
            kind,
            flags: 0,
            source,
            destination,
            message_id,
            chunk_index: 0,
            chunk_count: 1,
            body,
        }
    }

    /// Build a [`FrameKind::Data`] frame for one chunk of a message.
    #[must_use]
    pub fn data(
        source: Uuid,
        destination: Uuid,
        message_id: u64,
        chunk_index: u32,
        chunk_count: u32,
        body: Bytes,
    ) -> Self {
        let mut flags = 0;
        if chunk_index + 1 == chunk_count {
            flags |= FLAG_LAST_CHUNK;
        }
        Self {
            protocol_version: PROTOCOL_VERSION,
            kind: FrameKind::Data,
            flags,
            source,
            destination,
            message_id,
            chunk_index,
            chunk_count,
            body,
        }
    }

    /// Build a [`FrameKind::Ping`] frame with an empty body.
    #[must_use]
    pub fn ping(source: Uuid, destination: Uuid, message_id: u64) -> Self {
        Self::new(
            FrameKind::Ping,
            source,
            destination,
            message_id,
            Bytes::new(),
        )
    }

    /// Build a [`FrameKind::Pong`] frame with an empty body.
    #[must_use]
    pub fn pong(source: Uuid, destination: Uuid, message_id: u64) -> Self {
        Self::new(
            FrameKind::Pong,
            source,
            destination,
            message_id,
            Bytes::new(),
        )
    }

    /// Build a [`FrameKind::RelayError`] frame whose body is the single
    /// [`RelayErrorCode`] byte. `source` is the relay's own id; `destination`
    /// is the client being told about the error.
    #[must_use]
    pub fn relay_error(
        source: Uuid,
        destination: Uuid,
        message_id: u64,
        code: RelayErrorCode,
    ) -> Self {
        Self::new(
            FrameKind::RelayError,
            source,
            destination,
            message_id,
            Bytes::from(vec![code.as_u8()]),
        )
    }

    /// If this is a well-formed [`FrameKind::RelayError`] frame, return its
    /// [`RelayErrorCode`]. Returns `None` for other kinds or malformed bodies.
    #[must_use]
    pub fn relay_error_code(&self) -> Option<RelayErrorCode> {
        if self.kind != FrameKind::RelayError {
            return None;
        }
        let &[byte] = self.body.as_ref() else {
            return None;
        };
        RelayErrorCode::from_u8(byte)
    }

    /// Number of bytes this frame occupies when encoded.
    #[must_use]
    pub fn encoded_len(&self) -> usize {
        HEADER_LEN + self.body.len()
    }

    /// Validate the frame's invariants without encoding it.
    ///
    /// Checks protocol version, flag bits, body size, and non-nil ids. The
    /// `kind` field is a typed enum so it is always a known kind here.
    pub fn validate(&self) -> Result<(), WireError> {
        if self.protocol_version != PROTOCOL_VERSION {
            return Err(WireError::UnknownVersion(self.protocol_version));
        }
        if self.flags & !KNOWN_FLAGS != 0 {
            return Err(WireError::ReservedFlags(self.flags));
        }
        if self.body.len() > MAX_BODY_LEN {
            return Err(WireError::Oversized {
                len: self.body.len(),
                max: MAX_BODY_LEN,
            });
        }
        if self.source.is_nil() {
            return Err(WireError::NilSourceId);
        }
        if self.destination.is_nil() {
            return Err(WireError::NilDestinationId);
        }
        Ok(())
    }

    /// Encode the frame into a freshly allocated [`Bytes`].
    pub fn encode(&self) -> Result<Bytes, WireError> {
        let mut buf = BytesMut::with_capacity(self.encoded_len());
        self.encode_to(&mut buf)?;
        Ok(buf.freeze())
    }

    /// Encode the frame by appending to `dst`. Validates first, so on error
    /// `dst` is left unmodified.
    pub fn encode_to(&self, dst: &mut BytesMut) -> Result<(), WireError> {
        self.validate()?;

        let body_len = self.body.len();
        // Safe: MIN_FRAME_LEN + body_len <= MAX_FRAME_LEN which is well under u32.
        let frame_len = (MIN_FRAME_LEN + body_len) as u32;

        dst.reserve(self.encoded_len());
        dst.put_u32_le(frame_len);
        dst.put_u16_le(self.protocol_version);
        dst.put_u8(self.kind.as_u8());
        dst.put_u8(self.flags);
        dst.put_slice(self.source.as_bytes());
        dst.put_slice(self.destination.as_bytes());
        dst.put_u64_le(self.message_id);
        dst.put_u32_le(self.chunk_index);
        dst.put_u32_le(self.chunk_count);
        dst.put_u32_le(body_len as u32);
        dst.put_slice(&self.body);
        Ok(())
    }

    /// Attempt to decode one frame from the front of `src`.
    ///
    /// * `Ok(Some(frame))` — one complete, valid frame was decoded and consumed
    ///   from `src`. The body is a zero-copy slice of `src`'s buffer.
    /// * `Ok(None)` — `src` does not yet hold a complete frame; the caller
    ///   should read more bytes and retry. `src` is left unmodified.
    /// * `Err(_)` — the bytes present are structurally invalid; the frame (if
    ///   its declared length is known and present) is consumed so the caller
    ///   can resynchronize, otherwise `src` is left unmodified.
    pub fn decode(src: &mut Bytes) -> Result<Option<RelayFrame>, WireError> {
        if src.len() < FRAME_LEN_PREFIX {
            return Ok(None);
        }

        // Peek the length prefix without consuming.
        let frame_len = u32::from_le_bytes([src[0], src[1], src[2], src[3]]) as usize;

        // Structurally too small to contain a full header.
        if frame_len < MIN_FRAME_LEN {
            return Err(WireError::Truncated {
                have: FRAME_LEN_PREFIX + frame_len,
                need: HEADER_LEN,
            });
        }
        // Oversized: refuse before waiting for (or allocating) the whole frame.
        if frame_len > MAX_FRAME_LEN {
            return Err(WireError::Oversized {
                len: frame_len - MIN_FRAME_LEN,
                max: MAX_BODY_LEN,
            });
        }

        let total = FRAME_LEN_PREFIX + frame_len;
        if src.len() < total {
            return Ok(None);
        }

        // Consume exactly one frame; `frame` shares `src`'s buffer (zero-copy).
        let mut frame = src.split_to(total);
        Self::decode_header_and_body(&mut frame, frame_len).map(Some)
    }

    /// Decode exactly one frame from a buffer that is expected to contain a
    /// single complete frame and nothing more. Convenience over [`decode`]
    /// for callers that already have a framed message.
    ///
    /// [`decode`]: RelayFrame::decode
    pub fn decode_exact(src: Bytes) -> Result<RelayFrame, WireError> {
        let mut src = src;
        match Self::decode(&mut src)? {
            Some(frame) if src.is_empty() => Ok(frame),
            Some(_) => Err(WireError::LengthMismatch {
                declared: 0,
                actual: src.len(),
            }),
            None => Err(WireError::Truncated {
                have: src.len(),
                need: HEADER_LEN,
            }),
        }
    }

    /// Parse the header fields from `frame` (which is exactly one frame,
    /// `frame_len + 4` bytes) and validate. On success, the trailing bytes of
    /// `frame` become the zero-copy body.
    fn decode_header_and_body(
        frame: &mut Bytes,
        frame_len: usize,
    ) -> Result<RelayFrame, WireError> {
        // Consume the length prefix we already peeked.
        let _ = frame.get_u32_le();

        let protocol_version = frame.get_u16_le();
        let kind_byte = frame.get_u8();
        let flags = frame.get_u8();

        let mut src_bytes = [0u8; 16];
        frame.copy_to_slice(&mut src_bytes);
        let source = Uuid::from_bytes(src_bytes);

        let mut dst_bytes = [0u8; 16];
        frame.copy_to_slice(&mut dst_bytes);
        let destination = Uuid::from_bytes(dst_bytes);

        let message_id = frame.get_u64_le();
        let chunk_index = frame.get_u32_le();
        let chunk_count = frame.get_u32_le();
        let body_len = frame.get_u32_le() as usize;

        // Remaining bytes are the body, zero-copy.
        let body = std::mem::take(frame);

        // The length prefix and the body_len field must agree, and the body_len
        // field must match how many body bytes we actually have.
        let expected_body = frame_len - MIN_FRAME_LEN;
        if body_len != expected_body || body.len() != body_len {
            return Err(WireError::LengthMismatch {
                declared: body_len,
                actual: body.len(),
            });
        }

        if protocol_version != PROTOCOL_VERSION {
            return Err(WireError::UnknownVersion(protocol_version));
        }
        let kind = FrameKind::from_u8(kind_byte).ok_or(WireError::UnknownFrameKind(kind_byte))?;
        if flags & !KNOWN_FLAGS != 0 {
            return Err(WireError::ReservedFlags(flags));
        }
        if source.is_nil() {
            return Err(WireError::NilSourceId);
        }
        if destination.is_nil() {
            return Err(WireError::NilDestinationId);
        }

        Ok(RelayFrame {
            protocol_version,
            kind,
            flags,
            source,
            destination,
            message_id,
            chunk_index,
            chunk_count,
            body,
        })
    }
}
