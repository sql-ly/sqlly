/// Render every staged description change in the engine's own comment DDL,
/// appended after the structural body. Returns the honest per-engine error
/// when a staged change has no server-side form (SQLite/libSQL, MySQL views),
/// and refuses outright when the live descriptions could not be read — the
/// add-vs-update choice (SQL Server) and the "unchanged" check both depend
/// on knowing the current value.
pub(crate) fn render_comment_changes(
    db: DatabaseType,
    snapshot: &TableSnapshot,
    set: &ChangeSet,
    draft: &TableDraft,
) -> Result<String, AlterError> {
    let mut out = String::new();
    let staged = collect_changes(set, is_set_comment);
    if let (Some(reason), false) = (&snapshot.comment_read_error, staged.is_empty()) {
        return Err(AlterError::Localized(
            sqlly_core::DisplayMessage::new(
                "services.alter.errors.descriptions_unreadable",
                format!("The current descriptions could not be read ({reason}); reopen the editor before changing them."),
            )
            .with_arg("detail", reason),
        ));
    }
    for c in staged {
        if let Change::SetComment { column, from, to } = c {
            let change = comments::CommentChange {
                column: column.clone(),
                from: from.clone(),
                to: to.clone(),
            };
            match comments::render_comment_change_detailed(
                db,
                set.table.schema.as_deref(),
                &set.table.table,
                comments::CommentObjectKind::Table,
                &change,
                draft.source_ddl.as_deref(),
            ) {
                Ok(Some(sql)) => out.push_str(&sql),
                Ok(None) => {}
                Err(reason) => return Err(AlterError::Localized(reason)),
            }
        }
    }
    Ok(out)
}

/// Views that must be dropped before and recreated after a column change.
/// Returns `(drop_sql, create_sql, manual_review)`; views without a fetched
/// definition are neither dropped nor recreated — they go to manual review.
pub(crate) fn dependent_view_wrap(
    db: DatabaseType,
    views: &[DependentView],
) -> (String, String, Vec<String>) {
    let mut drop = String::new();
    let mut create = String::new();
    let mut review = Vec::new();
    for v in views.iter().rev() {
        let q = qualified_table(db, v.schema.as_deref(), &v.name);
        match &v.definition {
            Some(_) => {
                let kind = if v.materialized {
                    "MATERIALIZED VIEW"
                } else {
                    "VIEW"
                };
                drop.push_str(&format!("DROP {kind} {q};\n"));
            }
            None => {
                review.push(format!(
                    "View {q} references this table but its definition could not be read; recreate it manually"
                ));
            }
        }
    }
    for v in views {
        if let Some(def) = &v.definition {
            let def = def.trim_end().trim_end_matches(';');
            create.push_str(&format!("{def};\n"));
        }
    }
    (drop, create, review)
}

pub(crate) fn nested_view_warning(views: &[DependentView]) -> Option<String> {
    if views.len() > 1 {
        Some(
            "Multiple dependent views are recreated in catalog order; nested views may need manual reordering"
                .to_string(),
        )
    } else {
        None
    }
}

pub(crate) fn apply_view_wrap(
    db: DatabaseType,
    snapshot: &TableSnapshot,
    set: &ChangeSet,
    warnings: &mut Vec<String>,
    manual_review: &mut Vec<String>,
) -> (String, String) {
    if !touches_columns(set) || snapshot.dependent_views.is_empty() {
        return (String::new(), String::new());
    }
    if let Some(w) = nested_view_warning(&snapshot.dependent_views) {
        warnings.push(w);
    }
    let (drop, create, review) = dependent_view_wrap(db, &snapshot.dependent_views);
    manual_review.extend(review);
    (drop, create)
}
