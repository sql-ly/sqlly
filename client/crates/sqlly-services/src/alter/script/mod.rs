#[derive(Debug, Clone, Default)]
pub struct RenderOptions {
    pub mysql_algorithm: Option<MysqlAlgorithm>,
    pub mysql_lock: Option<MysqlLock>,
    pub pg_using: BTreeMap<String, String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MysqlAlgorithm {
    Instant,
    Inplace,
    Copy,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MysqlLock {
    None,
    Shared,
    Exclusive,
}

#[derive(Debug, Clone)]
pub struct AlterScript {
    pub sql: String,
    pub warnings: Vec<String>,
}

#[derive(Debug, thiserror::Error)]
pub enum AlterError {
    #[error("The structure editor does not support this engine yet")]
    UnsupportedEngine,
    #[error("{0}")]
    Message(String),
    #[error("{0}")]
    Localized(sqlly_core::DisplayMessage),
}

impl AlterError {
    pub fn message(&self) -> sqlly_core::DisplayMessage {
        match self {
            Self::UnsupportedEngine => sqlly_core::DisplayMessage::new(
                "services.alter.errors.unsupported_engine",
                "The structure editor does not support this engine yet",
            ),
            Self::Message(detail) => sqlly_core::DisplayMessage::raw(detail),
            Self::Localized(message) => message.clone(),
        }
    }
}

pub fn render(
    db: DatabaseType,
    snapshot: &TableSnapshot,
    draft: &TableDraft,
    set: &ChangeSet,
    opts: &RenderOptions,
) -> Result<AlterScript, AlterError> {
    // DuckDB parses as PostgreSQL but alters tables on its own terms.
    if db == DatabaseType::DuckDb {
        return duckdb::render(db, snapshot, draft, set, opts);
    }
    // ClickHouse parses as the MySQL family but alters tables with its own
    // vocabulary (MODIFY COLUMN types, data-skipping indexes, no keys).
    if db.connection_kind() == ConnectionKind::ClickHouseHttp {
        return clickhouse::render(db, snapshot, draft, set, opts);
    }
    match db.family() {
        Dialect::SqlServer => tds::render(db, snapshot, draft, set, opts),
        Dialect::Postgres => pg::render(db, snapshot, draft, set, opts),
        Dialect::MySql => mysql::render(db, snapshot, draft, set, opts),
        Dialect::Sqlite => sqlite::render(db, snapshot, draft, set, opts),
        Dialect::Oracle => oracle::render(db, snapshot, draft, set, opts),
    }
}

pub(crate) fn qualified_table(db: DatabaseType, schema: Option<&str>, table: &str) -> String {
    match schema.filter(|s| !s.is_empty()) {
        Some(s) => format!("{}.{}", db.quote_identifier(s), db.quote_identifier(table)),
        None => db.quote_identifier(table),
    }
}

pub(crate) fn header(
    schema: Option<&str>,
    table: &str,
    warnings: &[String],
    manual_review: &[String],
) -> String {
    let qualified = match schema.filter(|s| !s.is_empty()) {
        Some(s) => format!("{s}.{table}"),
        None => table.to_string(),
    };
    let mut out = comment_line(&format!(
        "Generated by SQLLY structure editor for {qualified}. Review before running."
    ));
    for w in warnings {
        out.push_str(&comment_line(&format!("WARNING: {w}")));
    }
    for m in manual_review {
        out.push_str(&comment_line(&format!("MANUAL REVIEW: {m}")));
    }
    out
}

/// `-- text\n` with any line break in `text` flattened to a space, so an
/// identifier, server error message, or constraint carrying a newline can
/// never escape the comment and become executable script.
pub(crate) fn comment_line(text: &str) -> String {
    format!("-- {}\n", crate::script_set::comment_safe(text))
}

pub(crate) fn find_draft_column<'a>(
    draft: &'a TableDraft,
    name: &str,
) -> Option<&'a crate::alter::snapshot::ColumnDef> {
    draft
        .columns
        .iter()
        .find(|c| c.def.name == name)
        .map(|c| &c.def)
}

pub(crate) fn collect_changes(set: &ChangeSet, kind: fn(&Change) -> bool) -> Vec<&Change> {
    set.changes.iter().filter(|c| kind(c)).collect()
}

