/// The assembled script plus the non-fatal problems hit while building it.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct CreateScript {
    pub sql: String,
    pub warnings: Vec<String>,
    pub tables_scripted: usize,
    /// Foreign keys moved to `ALTER TABLE … ADD CONSTRAINT` after the creates
    /// because they close a dependency cycle.
    pub deferred_foreign_keys: usize,
}

/// Engines whose CREATE script is rendered from catalog snapshots (and can add
/// a foreign key after the fact with `ALTER TABLE … ADD CONSTRAINT`).
pub fn renders_from_snapshot(db: DatabaseType) -> bool {
    matches!(
        db.connection_kind(),
        ConnectionKind::Tds
            | ConnectionKind::PostgresWire
            | ConnectionKind::MySqlWire
            | ConnectionKind::OracleNet
    )
}

fn script_header(database: &str, count: usize) -> String {
    format!(
        "-- CREATE script for {count} table(s) in {database}, generated by SQLLY's relationship diagram.\n-- Review before running; tables are ordered so referenced tables come first.\n"
    )
}

fn snapshot_key(snapshot: &TableSnapshot) -> String {
    table_key(snapshot.schema.as_deref().unwrap_or(""), &snapshot.table)
}

/// The referenced table's key, resolving an unqualified reference against the
/// child table's own schema.
fn fk_parent_key(child: &TableSnapshot, fk: &ForeignKeyDef) -> String {
    let schema = fk
        .ref_schema
        .as_deref()
        .filter(|s| !s.is_empty())
        .or(child.schema.as_deref())
        .unwrap_or("");
    table_key(schema, &fk.ref_table)
}

/// Normalise a referential action to its keyword form. Catalog text can carry
/// underscores (`NO_ACTION`) or trailing words from the surrounding DDL; the
/// engine default `NO ACTION` renders as nothing.
fn normalize_action(raw: &str) -> Option<&'static str> {
    let upper = raw.trim().replace('_', " ").to_ascii_uppercase();
    if upper.starts_with("CASCADE") {
        Some("CASCADE")
    } else if upper.starts_with("SET NULL") {
        Some("SET NULL")
    } else if upper.starts_with("SET DEFAULT") {
        Some("SET DEFAULT")
    } else if upper.starts_with("RESTRICT") {
        Some("RESTRICT")
    } else {
        None
    }
}

/// `CONSTRAINT name FOREIGN KEY (…) REFERENCES parent (…) [ON DELETE …] [ON UPDATE …]`
/// in the engine's accepted subset; unsupported actions are dropped with a
/// warning rather than producing a script that fails.
fn fk_constraint(db: DatabaseType, fk: &ForeignKeyDef, warnings: &mut Vec<String>) -> String {
    let quote_list = |cols: &[String]| {
        cols.iter()
            .map(|c| db.quote_identifier(c))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let mut sql = format!(
        "CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({})",
        db.quote_identifier(&fk.name),
        quote_list(&fk.columns),
        qualified_table(db, fk.ref_schema.as_deref(), &fk.ref_table),
        quote_list(&fk.ref_columns)
    );
    let family = db.family();
    if let Some(action) = fk.on_delete.as_deref().and_then(normalize_action) {
        let supported = match family {
            Dialect::SqlServer => action != "RESTRICT",
            Dialect::Oracle => matches!(action, "CASCADE" | "SET NULL"),
            _ => true,
        };
        if supported {
            sql.push_str(&format!(" ON DELETE {action}"));
        } else {
            warnings.push(format!(
                "Foreign key {}: ON DELETE {action} is not supported on {}; omitted",
                fk.name,
                db.display_name()
            ));
        }
    }
    if let Some(action) = fk.on_update.as_deref().and_then(normalize_action) {
        let supported = match family {
            Dialect::SqlServer => action != "RESTRICT",
            Dialect::Oracle => false,
            _ => true,
        };
        if supported {
            sql.push_str(&format!(" ON UPDATE {action}"));
        } else {
            warnings.push(format!(
                "Foreign key {}: ON UPDATE {action} is not supported on {}; omitted",
                fk.name,
                db.display_name()
            ));
        }
    }
    sql
}

/// One column's definition line in the engine's CREATE TABLE spelling.
fn column_line(
    db: DatabaseType,
    snapshot: &TableSnapshot,
    col: &ColumnDef,
    warnings: &mut Vec<String>,
) -> String {
    let name = db.quote_identifier(&col.name);
    let extras = snapshot.column_extras.get(&col.name);
    let generated = extras.and_then(|e| e.generated.as_ref());
    let paren = |expr: &str| {
        let expr = expr.trim();
        if expr.starts_with('(') && expr.ends_with(')') {
            expr.to_string()
        } else {
            format!("({expr})")
        }
    };
    let mut s = format!("{name} {}", col.data_type);
    let null = if col.nullable { " NULL" } else { " NOT NULL" };
    match db.family() {
        Dialect::SqlServer => {
            // A computed column has no type, nullability, or default of its own.
            if let Some(g) = generated {
                let persisted = if g.stored { " PERSISTED" } else { "" };
                return format!("{name} AS {}{persisted}", paren(&g.expression));
            }
            if let Some(collation) = extras.and_then(|e| e.collation.as_deref()) {
                if tds::is_collation_name(collation) {
                    s.push_str(&format!(" COLLATE {collation}"));
                } else {
                    warnings.push(format!(
                        "{}.{}: collation {collation:?} is not a plain collation name; omitted",
                        snapshot.table, col.name
                    ));
                }
            }
            if col.identity {
                let (seed, increment) = extras
                    .and_then(|e| e.identity_seed_increment.clone())
                    .unwrap_or_else(|| ("1".to_string(), "1".to_string()));
                s.push_str(&format!(" IDENTITY({seed},{increment})"));
            }
            s.push_str(null);
            if let Some(def) = &col.default {
                if let Some(name) = &col.default_constraint_name {
                    s.push_str(&format!(" CONSTRAINT {}", db.quote_identifier(name)));
                }
                s.push_str(&format!(" DEFAULT {def}"));
            }
        }
        Dialect::MySql => {
            if let Some(g) = generated {
                let kind = if g.stored { "STORED" } else { "VIRTUAL" };
                s.push_str(&format!(
                    " GENERATED ALWAYS AS {} {kind}",
                    paren(&g.expression)
                ));
                s.push_str(null);
            } else {
                s.push_str(null);
                if let Some(def) = &col.default {
                    s.push_str(&format!(" DEFAULT {def}"));
                }
                if let Some(expr) = extras.and_then(|e| e.on_update.as_deref()) {
                    s.push_str(&format!(" ON UPDATE {expr}"));
                }
                if col.identity {
                    s.push_str(" AUTO_INCREMENT");
                }
            }
            if let Some(text) = snapshot.column_comments.get(&col.name) {
                s.push_str(&format!(" COMMENT {}", comments::string_literal(db, text)));
            }
        }
        Dialect::Oracle => {
            if let Some(g) = generated {
                s.push_str(&format!(
                    " GENERATED ALWAYS AS {} VIRTUAL",
                    paren(&g.expression)
                ));
            } else if col.identity {
                s.push_str(if extras.is_some_and(|e| e.identity_always) {
                    " GENERATED ALWAYS AS IDENTITY"
                } else {
                    " GENERATED BY DEFAULT AS IDENTITY"
                });
            } else if let Some(def) = &col.default {
                s.push_str(&format!(" DEFAULT {def}"));
            }
            if !col.nullable {
                s.push_str(" NOT NULL");
            }
        }
        _ => {
            if let Some(g) = generated {
                let kind = if g.stored { "STORED" } else { "VIRTUAL" };
                s.push_str(&format!(
                    " GENERATED ALWAYS AS {} {kind}",
                    paren(&g.expression)
                ));
            } else if col.identity {
                s.push_str(if extras.is_some_and(|e| e.identity_always) {
                    " GENERATED ALWAYS AS IDENTITY"
                } else {
                    " GENERATED BY DEFAULT AS IDENTITY"
                });
            }
            s.push_str(null);
            if !col.identity
                && generated.is_none()
                && let Some(def) = &col.default
            {
                if def.to_ascii_lowercase().contains("nextval(") {
                    warnings.push(format!(
                        "{}.{}: default {def} needs its sequence to exist before this script runs",
                        snapshot.table, col.name
                    ));
                }
                s.push_str(&format!(" DEFAULT {def}"));
            }
        }
    }
    s
}

/// SQL Server's post-column table clauses: `ON [fg]`, `TEXTIMAGE_ON [fg]`,
/// and `WITH (DATA_COMPRESSION = …)`, in the order CREATE TABLE takes them.
fn tds_storage_clauses(db: DatabaseType, snapshot: &TableSnapshot) -> String {
    let storage = &snapshot.storage;
    let mut out = String::new();
    if let Some(fg) = &storage.filegroup {
        out.push_str(&format!(" ON {}", db.quote_identifier(fg)));
    }
    if let Some(fg) = &storage.lob_filegroup {
        out.push_str(&format!(" TEXTIMAGE_ON {}", db.quote_identifier(fg)));
    }
    if let Some(compression) = storage
        .data_compression
        .as_deref()
        .filter(|c| matches!(*c, "ROW" | "PAGE"))
    {
        out.push_str(&format!(" WITH (DATA_COMPRESSION = {compression})"));
    }
    out
}

/// Where a foreign key goes in the script.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum FkPlacement {
    /// Inside the CREATE TABLE: its parent exists already (created earlier,
    /// the table itself, or outside the scripted set).
    Inline,
    /// `ALTER TABLE … ADD` after every CREATE: it closes a dependency cycle.
    Deferred,
    /// Commented out: its parent was chosen but could not be scripted.
    ParentSkipped,
}

struct FkContext<'a> {
    in_set: &'a HashSet<String>,
    created: &'a HashSet<String>,
    skipped: &'a HashSet<String>,
}

impl FkContext<'_> {
    fn place(&self, key: &str, parent: &str) -> FkPlacement {
        if self.skipped.contains(parent) {
            FkPlacement::ParentSkipped
        } else if self.in_set.contains(parent) && parent != key && !self.created.contains(parent) {
            FkPlacement::Deferred
        } else {
            FkPlacement::Inline
        }
    }
}

/// `ALTER TABLE t ADD <constraint>;` statements, split by placement.
#[derive(Default)]
struct PostCreate {
    deferred: Vec<String>,
    parent_skipped: Vec<String>,
}

/// Render dependency-ordered CREATE TABLE DDL for `ordered` snapshots
/// (parents first, as [`order_tables`] returns them). Foreign keys that would
/// reference a table later in the list are deferred to `ALTER TABLE … ADD
/// CONSTRAINT` statements after every table is created. `skipped` holds the
/// keys of chosen tables that could not be read: foreign keys to them are
/// written commented out (with a warning) so the script still runs.
pub fn render_create_tables(
    db: DatabaseType,
    ordered: &[TableSnapshot],
    skipped: &HashSet<String>,
) -> CreateScript {
    let mut warnings = Vec::new();
    let in_set: HashSet<String> = ordered.iter().map(snapshot_key).collect();
    let mut created: HashSet<String> = HashSet::new();
    let mut post = PostCreate::default();
    let mut sql = String::new();
    let family = db.family();

    for snapshot in ordered {
        let key = snapshot_key(snapshot);
        for w in &snapshot.load_warnings {
            warnings.push(format!("{key}: {w}"));
        }
        let ctx = FkContext {
            in_set: &in_set,
            created: &created,
            skipped,
        };
        let replayed = if family == Dialect::MySql {
            snapshot
                .stored_table_ddl
                .as_deref()
                .and_then(|ddl| mysql_replay(ddl, snapshot, &key, &ctx, &mut post, &mut warnings))
        } else {
            None
        };
        match replayed {
            Some(text) => sql.push_str(&text),
            None => {
                if family == Dialect::MySql {
                    warnings.push(format!(
                        "{key}: SHOW CREATE TABLE was unavailable, so this table is rebuilt from the catalog (character sets, collations, CHECK constraints, and table options are not included)"
                    ));
                }
                render_from_snapshot(db, snapshot, &key, &ctx, &mut post, &mut sql, &mut warnings);
            }
        }
        write_separator(&mut sql, db);
        created.insert(key);
    }

    if !post.deferred.is_empty() {
        sql.push_str(
            "-- Foreign keys that close a dependency cycle, added once every table exists.\n",
        );
        for stmt in &post.deferred {
            sql.push_str(stmt);
            sql.push('\n');
            write_separator(&mut sql, db);
        }
    }
    if !post.parent_skipped.is_empty() {
        sql.push_str(
            "-- Foreign keys to tables that could not be scripted; add them once those tables exist.\n",
        );
        for stmt in &post.parent_skipped {
            sql.push_str(&comment_line(stmt));
        }
    }

    CreateScript {
        sql,
        warnings,
        tables_scripted: ordered.len(),
        deferred_foreign_keys: post.deferred.len(),
    }
}

/// One table's CREATE (plus, off MySQL, its indexes and descriptions) built
/// from the typed snapshot.
fn render_from_snapshot(
    db: DatabaseType,
    snapshot: &TableSnapshot,
    key: &str,
    ctx: &FkContext<'_>,
    post: &mut PostCreate,
    sql: &mut String,
    warnings: &mut Vec<String>,
) {
    let family = db.family();
    let table_q = qualified_table(db, snapshot.schema.as_deref(), &snapshot.table);
    let mut lines: Vec<String> = snapshot
        .columns
        .iter()
        .map(|c| column_line(db, snapshot, c, warnings))
        .collect();
    if !snapshot.primary_key.is_empty() {
        let cols = snapshot
            .primary_key
            .iter()
            .map(|c| db.quote_identifier(c))
            .collect::<Vec<_>>()
            .join(", ");
        match (&snapshot.pk_constraint_name, family) {
            // MySQL names every primary key PRIMARY; naming it is an error.
            (Some(name), f) if f != Dialect::MySql && !name.is_empty() => lines.push(format!(
                "CONSTRAINT {} PRIMARY KEY ({cols})",
                db.quote_identifier(name)
            )),
            _ => lines.push(format!("PRIMARY KEY ({cols})")),
        }
    }
    if family == Dialect::MySql {
        for idx in &snapshot.indexes {
            let clause = mysql::render_add_index(db, idx, warnings);
            lines.push(clause.trim_start_matches("ADD ").to_string());
        }
    }
    for check in &snapshot.check_constraints {
        lines.push(match &check.name {
            Some(name) => format!(
                "CONSTRAINT {} CHECK {}",
                db.quote_identifier(name),
                check.expression
            ),
            None => format!("CHECK {}", check.expression),
        });
    }
    for fk in &snapshot.foreign_keys {
        let parent = fk_parent_key(snapshot, fk);
        let constraint = fk_constraint(db, fk, warnings);
        match ctx.place(key, &parent) {
            FkPlacement::Inline => lines.push(constraint),
            FkPlacement::Deferred => post
                .deferred
                .push(format!("ALTER TABLE {table_q} ADD {constraint};")),
            FkPlacement::ParentSkipped => {
                warnings.push(format!(
                    "{key}: foreign key {} references {parent}, which could not be scripted; it is left commented out at the end",
                    fk.name
                ));
                post.parent_skipped
                    .push(format!("ALTER TABLE {table_q} ADD {constraint};"));
            }
        }
    }

    sql.push_str(&format!("CREATE TABLE {table_q} (\n    "));
    sql.push_str(&lines.join(",\n    "));
    sql.push_str("\n)");
    if family == Dialect::SqlServer {
        sql.push_str(&tds_storage_clauses(db, snapshot));
    }
    for feature in &snapshot.storage.unscripted {
        warnings.push(format!("{key}: {feature}"));
    }
    if family == Dialect::MySql
        && let Some(text) = &snapshot.table_comment
    {
        sql.push_str(&format!(
            " COMMENT = {}",
            comments::string_literal(db, text)
        ));
    }
    sql.push_str(";\n");

    if family != Dialect::MySql {
        let table_q = qualified_table(db, snapshot.schema.as_deref(), &snapshot.table);
        for idx in &snapshot.indexes {
            let stmt = match family {
                Dialect::SqlServer => tds::render_create_index(
                    db,
                    &table_q,
                    idx,
                    snapshot
                        .storage
                        .index_compression
                        .get(&idx.name)
                        .map(String::as_str),
                    warnings,
                ),
                Dialect::Oracle => oracle::render_create_index(db, &table_q, idx),
                _ => pg::render_create_index(db, &table_q, idx, warnings),
            };
            sql.push_str(&stmt);
        }
        for ddl in &snapshot.opaque_index_ddl {
            sql.push_str(ddl.trim_end());
            sql.push('\n');
        }
        let mut comment_changes = Vec::new();
        if let Some(text) = snapshot.table_comment.as_ref().filter(|t| !t.is_empty()) {
            comment_changes.push(CommentChange {
                column: None,
                from: None,
                to: Some(text.clone()),
            });
        }
        for col in &snapshot.columns {
            if let Some(text) = snapshot
                .column_comments
                .get(&col.name)
                .filter(|t| !t.is_empty())
            {
                comment_changes.push(CommentChange {
                    column: Some(col.name.clone()),
                    from: None,
                    to: Some(text.clone()),
                });
            }
        }
        for change in &comment_changes {
            match render_comment_change(
                db,
                snapshot.schema.as_deref(),
                &snapshot.table,
                CommentObjectKind::Table,
                change,
                None,
            ) {
                Ok(Some(stmt)) => sql.push_str(&stmt),
                Ok(None) => {}
                Err(reason) => warnings.push(format!("{key}: {reason}")),
            }
        }
    }
}

/// Replay a MySQL/MariaDB `SHOW CREATE TABLE` text: the engine's own column
/// spellings, CHECK constraints, charsets, and table options survive
/// verbatim. Foreign-key lines whose parent is not created yet move to
/// `ALTER TABLE … ADD` after every CREATE (or, for a skipped parent, a
/// commented-out one); the per-row `AUTO_INCREMENT=n` counter is dropped so
/// an empty copy starts at 1. `None` when the text does not have the
/// expected one-element-per-line shape — the caller then renders from the
/// snapshot.
fn mysql_replay(
    ddl: &str,
    snapshot: &TableSnapshot,
    key: &str,
    ctx: &FkContext<'_>,
    post: &mut PostCreate,
    warnings: &mut Vec<String>,
) -> Option<String> {
    let lines: Vec<&str> = ddl.lines().collect();
    let head = lines.first()?.trim_end();
    let table_ident = head.strip_prefix("CREATE TABLE ")?.strip_suffix(" (")?;
    let tail_at = lines
        .iter()
        .enumerate()
        .skip(1)
        .find(|(_, l)| l.starts_with(')'))
        .map(|(i, _)| i)?;
    let mut kept: Vec<String> = Vec::new();
    for line in &lines[1..tail_at] {
        let element = line.trim().trim_end_matches(',').trim_end();
        if element.is_empty() {
            continue;
        }
        let fk = mysql_fk_name(element)
            .and_then(|name| snapshot.foreign_keys.iter().find(|fk| fk.name == name));
        let placement = match fk {
            Some(fk) => ctx.place(key, &fk_parent_key(snapshot, fk)),
            None => FkPlacement::Inline,
        };
        match placement {
            FkPlacement::Inline => kept.push(format!("  {element}")),
            FkPlacement::Deferred => post
                .deferred
                .push(format!("ALTER TABLE {table_ident} ADD {element};")),
            FkPlacement::ParentSkipped => {
                let fk = fk?;
                warnings.push(format!(
                    "{key}: foreign key {} references {}, which could not be scripted; it is left commented out at the end",
                    fk.name,
                    fk_parent_key(snapshot, fk)
                ));
                post.parent_skipped
                    .push(format!("ALTER TABLE {table_ident} ADD {element};"));
            }
        }
    }
    if kept.is_empty() {
        return None;
    }
    let tail = strip_auto_increment_option(&lines[tail_at..].join("\n"));
    Some(format!(
        "{head}\n{}\n{};\n",
        kept.join(",\n"),
        tail.trim_end()
    ))
}

/// The constraint name of a `CONSTRAINT `name` FOREIGN KEY …` body line.
fn mysql_fk_name(element: &str) -> Option<String> {
    let rest = element.strip_prefix("CONSTRAINT `")?;
    let mut name = String::new();
    let mut chars = rest.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '`' {
            if chars.peek() == Some(&'`') {
                chars.next();
                name.push('`');
                continue;
            }
            let after: String = chars.collect();
            return after
                .trim_start()
                .starts_with("FOREIGN KEY")
                .then_some(name);
        }
        name.push(c);
    }
    None
}

/// Drop the ` AUTO_INCREMENT=n` table option (the live counter) from a
/// `SHOW CREATE TABLE` tail. Only an option outside quotes counts: the same
/// text inside a `COMMENT='…'` literal is the user's and stays.
fn strip_auto_increment_option(tail: &str) -> String {
    const OPTION: &str = " AUTO_INCREMENT=";
    let bytes = tail.as_bytes();
    let mut quote: Option<u8> = None;
    let mut i = 0;
    while i < bytes.len() {
        let b = bytes[i];
        match quote {
            Some(q) if b == q => {
                // A doubled quote is an escaped one, not the closing one.
                if bytes.get(i + 1) == Some(&q) {
                    i += 2;
                    continue;
                }
                quote = None;
            }
            Some(_) if b == b'\\' => i += 1,
            Some(_) => {}
            None if matches!(b, b'\'' | b'"' | b'`') => quote = Some(b),
            None if tail[i..].starts_with(OPTION) => {
                let after = i + OPTION.len();
                let digits = bytes[after..]
                    .iter()
                    .take_while(|b| b.is_ascii_digit())
                    .count();
                let end = after + digits;
                if digits > 0 && bytes.get(end).is_none_or(|b| b.is_ascii_whitespace()) {
                    return format!("{}{}", &tail[..i], &tail[end..]);
                }
            }
            None => {}
        }
        i += 1;
    }
    tail.to_string()
}

/// Build the relationship diagram's CREATE script for `tables` from live
/// catalog metadata. `fks` are the diagram's foreign-key rows, used for the
/// dependency order. Tables whose metadata cannot be read — including a
/// transport failure on one table — are written as `-- SKIPPED` comments
/// and reported, never aborting the run.
pub async fn script_tables_as_create(
    queries: &dyn QueryExecutor,
    profile: &ConnectionProfile,
    database: &str,
    tables: &[(String, String)],
    fks: &[ForeignKeyRow],
) -> StudioResult<CreateScript> {
    let db = profile.database_type;
    let order = order_tables(tables, fks);
    let mut warnings: Vec<String> = order
        .warnings
        .into_iter()
        .map(sqlly_core::DisplayMessage::into_fallback)
        .collect();
    warnings.extend(outside_selection_warnings(tables, fks));
    let mut skipped_sql = String::new();
    let mut skipped: HashSet<String> = HashSet::new();
    let lookup = |key: &String| {
        tables
            .iter()
            .find(|(schema, name)| table_key(schema, name) == *key)
            .cloned()
    };
    let mut skip = |key: &str, reason: &str, warnings: &mut Vec<String>| {
        warnings.push(format!("{key}: {reason}"));
        skipped_sql.push_str(&comment_line(&format!("SKIPPED {key}: {reason}")));
        skipped.insert(key.to_string());
    };

    let mut body = String::new();
    let mut scripted = 0;
    let mut deferred = 0;
    if renders_from_snapshot(db) {
        let mut snapshots = Vec::new();
        for key in &order.order {
            let Some((schema, name)) = lookup(key) else {
                continue;
            };
            let schema_arg = Some(schema.as_str()).filter(|s| !s.is_empty());
            match crate::table_snapshot::load_table_snapshot(
                queries, profile, database, schema_arg, &name,
            )
            .await
            {
                Ok(snapshot) if !snapshot.columns.is_empty() => snapshots.push(snapshot),
                Ok(_) => skip(key, "no columns found", &mut warnings),
                Err(err) => skip(key, &err.to_string(), &mut warnings),
            }
        }
        let rendered = render_create_tables(db, &snapshots, &skipped);
        warnings.extend(rendered.warnings);
        scripted = rendered.tables_scripted;
        deferred = rendered.deferred_foreign_keys;
        body.push_str(&rendered.sql);
    } else {
        for key in &order.order {
            let Some((schema, name)) = lookup(key) else {
                continue;
            };
            let target = NavigationTarget::Table {
                catalog: None,
                schema,
                name,
                clicked: ClickedRole::Table,
            };
            let doc = match fetch_ddl_document(queries, profile, database, &target).await {
                Ok(doc) => doc,
                Err(err) => {
                    skip(key, &err.to_string(), &mut warnings);
                    continue;
                }
            };
            match (doc.error.clone(), doc.primary_source()) {
                (Some(err), _) => skip(key, &err, &mut warnings),
                (None, Some(source)) if !source.body.trim().is_empty() => {
                    body.push_str(&terminate_stored_ddl(&source.body));
                    body.push('\n');
                    write_separator(&mut body, db);
                    scripted += 1;
                }
                _ => skip(key, "no definition available", &mut warnings),
            }
        }
        // The replayed text references its parents by name; one that could
        // not be scripted will make that CREATE (or a later insert) fail.
        for fk in fks {
            let child = table_key(&fk.from_schema, &fk.from_table);
            let parent = table_key(&fk.to_schema, &fk.to_table);
            if skipped.contains(&parent) && !skipped.contains(&child) && child != parent {
                let note = format!(
                    "{child}: references {parent}, which could not be scripted; create it before running this script"
                );
                if !warnings.contains(&note) {
                    warnings.push(note);
                }
            }
        }
    }

    let mut sql = script_header(database, tables.len());
    for warning in &warnings {
        sql.push_str(&comment_line(&format!("WARNING: {warning}")));
    }
    sql.push_str(&skipped_sql);
    sql.push('\n');
    sql.push_str(&body);
    Ok(CreateScript {
        sql,
        warnings,
        tables_scripted: scripted,
        deferred_foreign_keys: deferred,
    })
}

/// A replayed stored definition as runnable statements. SQLite's stored
/// `CREATE TABLE` has no terminating `;`, and the DDL document appends the
/// table's indexes after it as a `\n\n-- Indexes` section; without a `;`
/// between them the CREATE TABLE and the first CREATE INDEX run together
/// into one syntax error.
fn terminate_stored_ddl(text: &str) -> String {
    let text = text.trim_end();
    let (head, extras) = match text.find("\n\n-- ") {
        Some(at) => text.split_at(at),
        None => (text, ""),
    };
    let mut out = head.trim_end().to_string();
    if !out.ends_with(';') {
        out.push(';');
    }
    out.push_str(extras);
    let last = extras.lines().rev().find(|l| !l.trim().is_empty());
    if let Some(last) = last
        && !last.trim_start().starts_with("--")
        && !last.trim_end().ends_with(';')
    {
        out.push(';');
    }
    out
}

/// One warning per foreign key whose parent lies outside the chosen tables:
/// the script declares it but does not create the parent, so the parent
/// must already exist where the script runs.
fn outside_selection_warnings(tables: &[(String, String)], fks: &[ForeignKeyRow]) -> Vec<String> {
    let chosen: HashSet<String> = tables.iter().map(|(s, n)| table_key(s, n)).collect();
    let mut seen: HashSet<(String, String)> = HashSet::new();
    let mut out = Vec::new();
    for fk in fks {
        let child = table_key(&fk.from_schema, &fk.from_table);
        let parent = table_key(&fk.to_schema, &fk.to_table);
        if chosen.contains(&child)
            && !chosen.contains(&parent)
            && seen.insert((child.clone(), parent.clone()))
        {
            out.push(format!(
                "{child} references {parent}, which is not in this script; it must already exist where the script runs"
            ));
        }
    }
    out
}

