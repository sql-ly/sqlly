//! "Script as CREATE" for a set of tables (the relationship diagram's
//! forward-engineering output): dependency-ordered `CREATE TABLE` DDL plus the
//! tables' indexes, descriptions, and foreign keys, assembled as one script for
//! review in an editor tab. Nothing here executes anything.
//!
//! Two paths:
//! - **SQL Server, PostgreSQL-wire, MySQL/MariaDB, Oracle** render from catalog
//!   snapshots ([`render_create_tables`]). Tables are emitted parents-first; a
//!   foreign key whose parent is already created (or lies outside the chosen
//!   set, or is the table itself) is declared inline, and a foreign key that
//!   would reference a table not created yet — i.e. one that closes a
//!   dependency cycle — is deferred to an `ALTER TABLE … ADD CONSTRAINT` after
//!   every table exists.
//! - **SQLite/libSQL, DuckDB, ClickHouse** replay the engine's own stored
//!   `CREATE` text in dependency order. SQLite accepts forward references in
//!   foreign keys, DuckDB cannot create cyclic foreign keys at all, and
//!   ClickHouse has none — and the stored text keeps engine clauses (storage
//!   engine, `WITHOUT ROWID`, …) a snapshot does not model.

