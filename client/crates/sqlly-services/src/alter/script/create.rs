        /// Fails (at the transport level) any statement containing `fail_on`.
        struct PartlyFailing {
            inner: FakeQueries,
            fail_on: String,
        }

        #[async_trait]
        impl QueryExecutor for PartlyFailing {
            async fn execute(
                &self,
                profile: &ConnectionProfile,
                sql: &str,
                row_buffer: usize,
            ) -> StudioResult<QueryHandle> {
                if sql.contains(&self.fail_on) {
                    return Err(sqlly_core::StudioError::Connection(
                        "connection reset\nDROP TABLE parent;".into(),
                    ));
                }
                self.inner.execute(profile, sql, row_buffer).await
            }

            async fn cancel(&self, task_id: &str) -> StudioResult<()> {
                self.inner.cancel(task_id).await
            }
        }

        #[tokio::test]
        async fn a_transport_error_skips_that_table_without_aborting() {
            let queries = PartlyFailing {
                inner: FakeQueries {
                    routes: vec![ddl_route(
                        "parent",
                        "CREATE TABLE parent (id INTEGER PRIMARY KEY)",
                    )],
                },
                fail_on: "WHERE name = 'child'".into(),
            };
            let tables = vec![
                ("main".to_string(), "child".to_string()),
                ("main".to_string(), "parent".to_string()),
            ];
            let script = script_tables_as_create(
                &queries,
                &sqlite_profile(),
                "main",
                &tables,
                &[fk("child", "parent")],
            )
            .await
            .expect("one failing table must not abort the run");
            assert_eq!(script.tables_scripted, 1);
            assert!(script.sql.contains("CREATE TABLE parent"));
            assert!(
                script.sql.contains("-- SKIPPED main.child: "),
                "{}",
                script.sql
            );
            // The error text's newline stays inside the comment.
            assert!(
                !script.sql.lines().any(|l| l.trim() == "DROP TABLE parent;"),
                "{}",
                script.sql
            );
        }

