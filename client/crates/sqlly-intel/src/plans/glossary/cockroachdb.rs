//! CockroachDB operator glossary.
//!
//! Names are the node names of `EXPLAIN` and `EXPLAIN ANALYZE`, as listed in
//! `pkg/sql/opt/exec/explain/emit.go`. The parser keeps them as printed, lower
//! case and with any parenthesized qualifier (`hash join (inner)`,
//! `lookup join (anti) (streamer)`); the prefix rule of the lookup drops the
//! qualifiers. The grouping strategies (`group (hash)`) are operators of their
//! own. The hyphenated spellings are the ones older versions printed.

