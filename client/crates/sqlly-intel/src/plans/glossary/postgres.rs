//! PostgreSQL operator glossary.
//!
//! Node names follow `src/backend/commands/explain.c` through PostgreSQL 18.
//! The caller canonicalizes JSON plans to the text-format names (`ModifyTable`
//! by operation, `Aggregate` and `SetOp` by strategy) and strips the
//! `Parallel`, `Partial`, `Finalize` prefixes and the join-type words, so each
//! operator has one entry; the extra names are aliases for plans that arrive
//! without that step.

