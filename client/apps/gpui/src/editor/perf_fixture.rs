//! A synthetic data-import script for editor performance tests.
//!
//! Shaped like a real-world 0.5 MB T-SQL import that made the editor lag:
//! one transaction, a dozen temp tables, ~60 multi-row `INSERT … VALUES`
//! blocks carrying thousands of `N'…'` literals with accented text, staging
//! `UPDATE … INNER JOIN`s, `DECLARE`/`IF` plumbing, and lines up to ~740
//! characters. Generated deterministically (no data from the real script),
//! so the fixture costs nothing to keep in the repo.

/// Department names: accented, upper-case, repeated a lot — like the real
/// lookup columns.
const AREAS: &[&str] = &[
    "GERENCIA GENERAL",
    "GERENCIA DE OPERACIONES",
    "DIRECCIÓN DE FINANZAS",
    "ADMINISTRACIÓN Y CONTABILIDAD",
    "RECURSOS HUMANOS",
    "TECNOLOGÍA DE LA INFORMACIÓN",
    "LOGÍSTICA Y DISTRIBUCIÓN",
    "ATENCIÓN AL CLIENTE",
    "SEGURIDAD E HIGIENE",
    "COMPRAS Y ABASTECIMIENTO",
];

const FIRST: &[&str] = &[
    "José", "María", "Ángel", "Lucía", "Martín", "Sofía", "Raúl", "Inés", "Andrés", "Núria",
    "Joaquín", "Begoña", "Íñigo", "Mónica", "Germán", "Zoë",
];

const LAST: &[&str] = &[
    "García",
    "Martínez",
    "López",
    "Sánchez",
    "Pérez",
    "Gómez",
    "Fernández",
    "Díaz",
    "Muñoz",
    "Álvarez",
    "Romero",
    "Gutiérrez",
    "Peña",
    "Ibáñez",
    "Castaño",
    "Núñez",
];

const ROLES: &[&str] = &[
    "Analista",
    "Supervisor de Turno",
    "Jefe de Área",
    "Técnico Especialista",
    "Auxiliar",
    "Coordinador Regional",
    "Gerente",
    "Asistente de Dirección",
];

/// Tiny deterministic PRNG so the fixture is byte-identical on every run.
struct Lcg(u64);

impl Lcg {
    fn next(&mut self) -> u64 {
        self.0 = self
            .0
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        self.0 >> 33
    }

    fn pick<'a>(&mut self, items: &[&'a str]) -> &'a str {
        items[(self.next() as usize) % items.len()]
    }
}

/// The synthetic import script (~3,900 lines, ~0.4 MB).
pub(crate) fn import_script() -> String {
    let mut rng = Lcg(0x5EED_1234);
    let mut out = String::with_capacity(450_000);
    out.push_str(
        "/*\n  Employee import generated by a migration tool.\n  Source: legacy HR export -- 340 areas, 2,900 people.\n  Review the staging tables before committing.\n*/\n\n",
    );
    out.push_str("SET NOCOUNT ON;\nSET XACT_ABORT ON;\n\nBEGIN TRANSACTION;\n\n");

    // Staging tables.
    let tables = [
        "#Areas",
        "#Puestos",
        "#Personas",
        "#Contratos",
        "#Domicilios",
        "#Contactos",
        "#Bancos",
        "#Beneficiarios",
        "#Turnos",
        "#Sedes",
        "#Jefaturas",
        "#Errores",
        "#Mapa",
    ];
    for t in tables {
        out.push_str(&format!(
            "CREATE TABLE {t} (\n    Id INT IDENTITY(1,1) PRIMARY KEY,\n    Codigo NVARCHAR(40) NOT NULL,\n    Nombre NVARCHAR(200) NOT NULL,\n    Descripcion NVARCHAR(400) NULL,\n    Area NVARCHAR(200) NULL,\n    Puesto NVARCHAR(200) NULL,\n    FechaAlta DATE NULL,\n    Activo BIT NOT NULL DEFAULT 1\n);\n\n"
        ));
    }

    // Variables.
    for i in 0..34 {
        out.push_str(&format!(
            "DECLARE @Paso{i} INT = 0, @Mensaje{i} NVARCHAR(400) = N'Paso {i}: sin cambios';\n"
        ));
    }
    out.push('\n');

    // The bulk: multi-row INSERTs. Most tuples sit one per line (~110
    // chars); every block also packs a few very long lines with several
    // tuples (up to ~740 chars), like the real export.
    let mut code = 0u32;
    for block in 0..63 {
        let table = tables[block % 9];
        out.push_str(&format!(
            "-- Lote {block}: {} registros para {table}\n",
            40 + block % 7
        ));
        out.push_str(&format!(
            "INSERT INTO {table} (Codigo, Nombre, Area, Puesto, FechaAlta, Activo)\nVALUES\n"
        ));
        let rows = 40 + (block % 6);
        for r in 0..rows {
            let per_line = if r % 9 == 4 { 6 } else { 1 };
            let mut line = String::from("    ");
            for k in 0..per_line {
                code += 1;
                let first = rng.pick(FIRST);
                let last = rng.pick(LAST);
                let area = rng.pick(AREAS);
                let role = rng.pick(ROLES);
                let day = 1 + rng.next() % 28;
                let month = 1 + rng.next() % 12;
                let year = 2005 + rng.next() % 20;
                if k > 0 {
                    line.push_str(", ");
                }
                line.push_str(&format!(
                    "(N'EMP-{code:06}', N'{first} {last}', N'{area}', N'{role}', '{year}-{month:02}-{day:02}', {})",
                    u8::from(!code.is_multiple_of(13))
                ));
            }
            let last_row = r + 1 == rows;
            line.push_str(if last_row { ";\n" } else { ",\n" });
            out.push_str(&line);
        }
        out.push('\n');

        // Staging fix-ups between blocks.
        if block % 4 == 0 {
            out.push_str(&format!(
                "UPDATE e\nSET e.Area = a.Nombre,\n    e.Descripcion = CONCAT(e.Descripcion, N' — revisado')\nFROM {table} AS e\nINNER JOIN #Areas AS a ON a.Codigo = e.Area\nINNER JOIN #Mapa AS m ON m.Codigo = e.Codigo\nWHERE e.Activo = 1;\n\n"
            ));
        }
        if block % 2 == 1 {
            let step = block % 34;
            out.push_str(&format!(
                "IF @@ROWCOUNT = 0\nBEGIN\n    SET @Paso{step} = @Paso{step} + 1;\n    SET @Mensaje{step} = N'Lote {block} vacío; se omitió.';\n    INSERT INTO #Errores (Codigo, Nombre) VALUES (N'L{block}', @Mensaje{step});\nEND\n\n"
            ));
        }
    }

    out.push_str(
        "SELECT e.Codigo, e.Nombre, a.Nombre AS Area\nFROM #Personas AS e\nINNER JOIN #Areas AS a ON a.Nombre = e.Area\nWHERE e.Activo = 1\nORDER BY a.Nombre, e.Nombre;\n\nCOMMIT TRANSACTION;\n",
    );
    out
}

#[cfg(test)]
mod tests {
    #[test]
    fn import_script_has_the_real_scripts_shape() {
        let sql = super::import_script();
        let lines = sql.lines().count();
        let longest = sql.lines().map(|l| l.chars().count()).max().unwrap_or(0);
        assert!(
            (300_000..=550_000).contains(&sql.len()),
            "bytes: {}",
            sql.len()
        );
        assert!((3_000..=5_000).contains(&lines), "lines: {lines}");
        assert!((600..=800).contains(&longest), "longest line: {longest}");
        assert!(sql.matches("N'").count() > 10_000);
        assert_eq!(sql, super::import_script(), "deterministic");
    }
}
