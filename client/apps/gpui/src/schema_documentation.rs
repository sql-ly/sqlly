//! Markdown data-dictionary generation from the loaded schema model.
//!
//! Pure text generation over [`ModelSnapshot`] — no server round trips, no
//! I/O. The caller decides where the document goes (a file the user picks).

use sqlly_lang::sqlmodel::{ModelSnapshot, ObjectBody, ObjectEntry, ObjectKind, ParamMode};

/// Objects beyond this count are summarized rather than documented in full in a
/// single document, so a pathological schema cannot produce an unbounded file.
/// [`generate_documentation`] instead splits past this point so nothing is lost.
const MAX_DOCUMENTED_OBJECTS: usize = 2_000;

/// One file of a (possibly multi-file) schema-documentation set.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DocFile {
    /// Filename suffix relative to the chosen base name: empty for the index /
    /// single document, or `.<schema>` for a per-schema file. Sanitized so it
    /// is always a safe filename segment.
    pub suffix: String,
    pub content: String,
}

/// Escape a value for use inside a Markdown table cell.
fn cell(value: &str) -> String {
    value.replace('|', "\\|").replace('\n', " ")
}

fn type_name(ty: &Option<sqlly_lang::sqlmodel::TypeRef>) -> String {
    ty.as_ref()
        .map(|ty| ty.native.clone())
        .unwrap_or_else(|| "?".to_string())
}

/// The generated data dictionary for a snapshot. `title` names the database
/// or connection the document describes.
pub fn generate_markdown(snapshot: &ModelSnapshot, title: &str) -> String {
    let mut objects: Vec<&ObjectEntry> = snapshot.objects().map(|entry| entry.as_ref()).collect();
    objects.sort_by(|a, b| {
        (kind_rank(a.kind), a.reference.display().to_lowercase())
            .cmp(&(kind_rank(b.kind), b.reference.display().to_lowercase()))
    });

    let truncated = objects.len() > MAX_DOCUMENTED_OBJECTS;
    let total = objects.len();
    if truncated {
        objects.truncate(MAX_DOCUMENTED_OBJECTS);
    }

    let mut out = format!(
        "# Data Dictionary — {title}\n\nGenerated by SQLLY from the loaded schema model. {total} objects.\n"
    );
    if truncated {
        out.push_str(&format!(
            "\n> Documented the first {MAX_DOCUMENTED_OBJECTS} objects; {} more omitted.\n",
            total - MAX_DOCUMENTED_OBJECTS
        ));
    }

    render_objects(&mut out, &objects);
    out
}

/// The schema segment (namespace) an object belongs to, or `"(default)"` when
/// it has none.
fn schema_of(entry: &ObjectEntry) -> String {
    entry
        .reference
        .namespace
        .as_ref()
        .map(|n| n.spelling().to_string())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "(default)".to_string())
}

/// Sanitize a schema name into a safe filename segment.
fn filename_segment(schema: &str) -> String {
    let cleaned: String = schema
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '-' || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    let trimmed = cleaned.trim_matches('_');
    if trimmed.is_empty() {
        "default".to_string()
    } else {
        trimmed.to_string()
    }
}

/// Generate the data dictionary as one or more files. Small models return a
/// single [`DocFile`] with an empty suffix (identical to [`generate_markdown`]).
/// Models larger than [`MAX_DOCUMENTED_OBJECTS`] are split into one file per
/// schema plus a linking index, so a large database is documented in full and
/// stays navigable instead of being truncated into one giant, capped file.
///
/// `base_name` and `extension` are the chosen file's actual stem and extension
/// (e.g. `schema-docs`, `md`), used VERBATIM in the index's links so they match
/// the sibling filenames the caller writes — a sanitized copy would point at
/// files that don't exist when the stem carries spaces or unicode. Link
/// destinations are wrapped in `<…>` so such stems still form valid Markdown.
pub fn generate_documentation(
    snapshot: &ModelSnapshot,
    title: &str,
    base_name: &str,
    extension: &str,
) -> Vec<DocFile> {
    let total = snapshot.objects().count();
    if total <= MAX_DOCUMENTED_OBJECTS {
        return vec![DocFile {
            suffix: String::new(),
            content: generate_markdown(snapshot, title),
        }];
    }

    // Group objects by schema, each group sorted like the single-file document.
    use std::collections::BTreeMap;
    let mut by_schema: BTreeMap<String, Vec<&ObjectEntry>> = BTreeMap::new();
    for entry in snapshot.objects() {
        by_schema
            .entry(schema_of(entry.as_ref()))
            .or_default()
            .push(entry.as_ref());
    }
    for objects in by_schema.values_mut() {
        objects.sort_by(|a, b| {
            (kind_rank(a.kind), a.reference.display().to_lowercase())
                .cmp(&(kind_rank(b.kind), b.reference.display().to_lowercase()))
        });
    }

    let mut files = Vec::with_capacity(by_schema.len() + 1);
    let mut index = format!(
        "# Data Dictionary — {title}\n\nGenerated by SQLLY from the loaded schema model. {total} objects across {} schemas, split one file per schema.\n\n## Schemas\n\n",
        by_schema.len()
    );
    // Distinct schemas can sanitize to the same filename segment (`a b` and
    // `a_b` both become `a_b`); suffix collisions would silently overwrite one
    // schema's file with another's, so disambiguate with a counter.
    let mut used_segments = std::collections::HashSet::new();
    for (schema, objects) in &by_schema {
        let base_segment = filename_segment(schema);
        let mut segment = base_segment.clone();
        let mut counter = 2;
        while !used_segments.insert(segment.clone()) {
            segment = format!("{base_segment}-{counter}");
            counter += 1;
        }
        index.push_str(&format!(
            "- [{schema}](<./{base_name}.{segment}.{extension}>) — {} objects\n",
            objects.len(),
        ));
        let mut content = format!("# Data Dictionary — {title} — {schema}\n\n");
        render_objects(&mut content, objects);
        files.push(DocFile {
            suffix: format!(".{segment}"),
            content,
        });
    }
    // Index first, so the caller writes it to the chosen path.
    files.insert(
        0,
        DocFile {
            suffix: String::new(),
            content: index,
        },
    );
    files
}

/// Render the sorted object list into `out` as Markdown sections/tables. Shared
/// by the single-file and per-schema documents.
fn render_objects(out: &mut String, objects: &[&ObjectEntry]) {
    let mut current_section = "";
    for entry in objects {
        let section = section_title(entry.kind);
        if section != current_section {
            current_section = section;
            out.push_str(&format!("\n## {section}\n"));
        }
        out.push_str(&format!("\n### {}\n\n", entry.reference.display()));
        match &entry.body {
            ObjectBody::Table(table) => {
                out.push_str(
                    "| Column | Type | Nullable | Default | Key |\n|---|---|---|---|---|\n",
                );
                for column in &table.columns {
                    let mut key = String::new();
                    if table.is_key_column(&column.name) {
                        key.push_str("PK");
                    }
                    if let Some(fk) = table.foreign_key_for_column(&column.name) {
                        if !key.is_empty() {
                            key.push_str(", ");
                        }
                        key.push_str(&format!("FK → {}", fk.target.display()));
                    }
                    if column.identity {
                        if !key.is_empty() {
                            key.push_str(", ");
                        }
                        key.push_str("identity");
                    }
                    out.push_str(&format!(
                        "| {} | {} | {} | {} | {} |\n",
                        cell(column.name.spelling()),
                        cell(&type_name(&column.ty)),
                        match column.nullable {
                            Some(true) => "yes",
                            Some(false) => "no",
                            None => "?",
                        },
                        cell(column.default.as_deref().unwrap_or("")),
                        cell(&key),
                    ));
                }
                if !table.foreign_keys.is_empty() {
                    out.push('\n');
                    for fk in &table.foreign_keys {
                        out.push_str(&format!(
                            "- Foreign key ({}) → {} ({})\n",
                            fk.columns
                                .iter()
                                .map(|c| c.spelling().to_string())
                                .collect::<Vec<_>>()
                                .join(", "),
                            fk.target.display(),
                            fk.target_columns
                                .iter()
                                .map(|c| c.spelling().to_string())
                                .collect::<Vec<_>>()
                                .join(", "),
                        ));
                    }
                }
            }
            ObjectBody::View(view) => {
                if view.columns.is_empty() {
                    out.push_str("Columns not recorded in the schema model.\n");
                } else {
                    out.push_str("| Column | Type |\n|---|---|\n");
                    for column in &view.columns {
                        out.push_str(&format!(
                            "| {} | {} |\n",
                            cell(column.name.spelling()),
                            cell(&type_name(&column.ty)),
                        ));
                    }
                }
            }
            ObjectBody::Routine(routine) => {
                if routine.params.is_empty() {
                    out.push_str("No parameters.\n");
                } else {
                    out.push_str("| Parameter | Type | Mode | Default |\n|---|---|---|---|\n");
                    for param in &routine.params {
                        out.push_str(&format!(
                            "| {} | {} | {} | {} |\n",
                            cell(param.name.spelling()),
                            cell(&type_name(&param.ty)),
                            match param.mode {
                                ParamMode::In => "in",
                                ParamMode::Out => "out",
                                ParamMode::InOut => "in/out",
                            },
                            cell(param.default.as_deref().unwrap_or("")),
                        ));
                    }
                }
                if let Some(returns) = &routine.returns {
                    out.push_str(&format!("\nReturns: {}\n", cell(&returns.native)));
                }
            }
            ObjectBody::Synonym { target } => {
                out.push_str(&format!("Synonym for {}\n", target.display()));
            }
            ObjectBody::Opaque => {
                out.push_str("No structural details recorded.\n");
            }
        }
    }
}

fn kind_rank(kind: ObjectKind) -> u8 {
    match kind {
        ObjectKind::Table => 0,
        ObjectKind::View | ObjectKind::MaterializedView => 1,
        ObjectKind::Procedure => 2,
        ObjectKind::Function
        | ObjectKind::ScalarFunction
        | ObjectKind::TableFunction
        | ObjectKind::AggregateFunction => 3,
        _ => 4,
    }
}

fn section_title(kind: ObjectKind) -> &'static str {
    match kind_rank(kind) {
        0 => "Tables",
        1 => "Views",
        2 => "Procedures",
        3 => "Functions",
        _ => "Other Objects",
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use sqlly_lang::sqlmodel::{
        ColumnDef, Dialect, Fidelity, KeyDef, ModelSnapshot, ObjectFragment, ObjectRef, ParamDef,
        Provenance, RoutineBody, SqlName, TableBody, TypeRef,
    };
    use std::collections::BTreeSet;

    fn name(value: &str) -> SqlName {
        SqlName::new(value, Dialect::SqlServer, false)
    }

    fn column(spelling: &str, ty: &str, nullable: bool, ordinal: usize) -> ColumnDef {
        ColumnDef {
            name: name(spelling),
            ty: Some(TypeRef::parse(ty, Dialect::SqlServer)),
            nullable: Some(nullable),
            default: None,
            identity: false,
            generated: None,
            collation: None,
            ordinal,
        }
    }

    fn snapshot(fragments: Vec<ObjectFragment>) -> ModelSnapshot {
        let (snapshot, _) = ModelSnapshot::empty().apply(
            1,
            fragments,
            &BTreeSet::new(),
            sqlly_lang::sqlmodel::IncompleteRegions::default(),
        );
        snapshot
    }

    #[test]
    fn documents_tables_with_columns_and_keys() {
        let table = ObjectFragment {
            reference: ObjectRef::new(None, Some(name("dbo")), name("Orders")),
            kind: ObjectKind::Table,
            dialect: Dialect::SqlServer,
            body: ObjectBody::Table(TableBody {
                columns: vec![
                    column("Id", "int", false, 0),
                    column("CustomerId", "int", true, 1),
                ],
                primary_key: Some(KeyDef {
                    name: None,
                    columns: vec![name("Id")],
                }),
                ..TableBody::default()
            }),
            provenance: Provenance::Database {
                profile: "p".into(),
            },
            fidelity: Fidelity::Exact,
            references: vec![],
        };
        let routine = ObjectFragment {
            reference: ObjectRef::new(None, Some(name("dbo")), name("GetOrders")),
            kind: ObjectKind::Procedure,
            dialect: Dialect::SqlServer,
            body: ObjectBody::Routine(RoutineBody {
                params: vec![ParamDef {
                    name: name("@CustomerId"),
                    ty: Some(TypeRef::parse("int", Dialect::SqlServer)),
                    mode: ParamMode::In,
                    default: None,
                }],
                returns: None,
                language: None,
                body_text: None,
            }),
            provenance: Provenance::Database {
                profile: "p".into(),
            },
            fidelity: Fidelity::Exact,
            references: vec![],
        };
        let doc = generate_markdown(&snapshot(vec![table, routine]), "Shop");
        assert!(doc.starts_with("# Data Dictionary — Shop"), "{doc}");
        assert!(doc.contains("## Tables"), "{doc}");
        assert!(doc.contains("### dbo.Orders"), "{doc}");
        assert!(doc.contains("| Id | int | no |"), "{doc}");
        assert!(doc.contains("PK"), "{doc}");
        assert!(doc.contains("| CustomerId | int | yes |"), "{doc}");
        assert!(doc.contains("## Procedures"), "{doc}");
        assert!(doc.contains("| @CustomerId | int | in |"), "{doc}");
    }

    #[test]
    fn escapes_pipes_in_defaults() {
        let escaped = cell("a|b");
        assert_eq!(escaped, "a\\|b");
    }

    #[test]
    fn empty_snapshot_still_produces_a_header() {
        let doc = generate_markdown(&ModelSnapshot::empty(), "Empty");
        assert!(doc.contains("0 objects"), "{doc}");
    }

    fn table_fragment(schema: &str, table: &str) -> ObjectFragment {
        ObjectFragment {
            reference: ObjectRef::new(None, Some(name(schema)), name(table)),
            kind: ObjectKind::Table,
            dialect: Dialect::SqlServer,
            body: ObjectBody::Table(TableBody {
                columns: vec![column("Id", "int", false, 0)],
                ..TableBody::default()
            }),
            provenance: Provenance::Database {
                profile: "p".into(),
            },
            fidelity: Fidelity::Exact,
            references: vec![],
        }
    }

    #[test]
    fn small_model_is_a_single_file() {
        let snap = snapshot(vec![table_fragment("dbo", "Orders")]);
        let files = generate_documentation(&snap, "Shop", "schema-docs", "md");
        assert_eq!(files.len(), 1);
        assert_eq!(files[0].suffix, "");
        assert!(files[0].content.contains("### dbo.Orders"));
    }

    #[test]
    fn large_model_splits_by_schema_with_a_linking_index() {
        // Exceed the single-file cap across two schemas.
        let mut fragments = Vec::new();
        for i in 0..(MAX_DOCUMENTED_OBJECTS + 10) {
            let schema = if i % 2 == 0 { "sales" } else { "hr" };
            fragments.push(table_fragment(schema, &format!("T{i}")));
        }
        let files = generate_documentation(&snapshot(fragments), "Big", "schema-docs", "md");
        // Index + one file per schema.
        assert_eq!(files.len(), 3);
        let index = &files[0];
        assert_eq!(index.suffix, "");
        assert!(
            index.content.contains("split one file per schema"),
            "{}",
            index.content
        );
        // Every per-schema link resolves to a produced filename.
        for file in &files[1..] {
            let filename = format!("schema-docs{}.md", file.suffix);
            assert!(
                index.content.contains(&filename),
                "index missing link to {filename}:\n{}",
                index.content
            );
        }
        // No object was dropped: total documented tables equals the input.
        let documented: usize = files[1..]
            .iter()
            .map(|f| f.content.matches("\n### ").count())
            .sum();
        assert_eq!(documented, MAX_DOCUMENTED_OBJECTS + 10);
    }

    /// Populate two schemas past the split threshold.
    fn two_schema_large_snapshot(a: &str, b: &str) -> ModelSnapshot {
        let mut fragments = Vec::new();
        for i in 0..(MAX_DOCUMENTED_OBJECTS + 2) {
            let schema = if i % 2 == 0 { a } else { b };
            fragments.push(table_fragment(schema, &format!("T{i}")));
        }
        snapshot(fragments)
    }

    #[test]
    fn index_links_use_the_chosen_stem_and_extension_verbatim() {
        // A stem with a space and a non-`md` extension must appear in the links
        // exactly as chosen — the caller writes files with the raw stem, so a
        // sanitized copy would point at files that don't exist.
        let files = generate_documentation(
            &two_schema_large_snapshot("sales", "hr"),
            "Big",
            "my docs",
            "markdown",
        );
        let index = &files[0];
        for file in &files[1..] {
            let filename = format!("my docs{}.markdown", file.suffix);
            assert!(
                index.content.contains(&format!("(<./{filename}>)")),
                "index missing bracketed link to {filename:?}:\n{}",
                index.content
            );
        }
    }

    #[test]
    fn colliding_schema_segments_get_distinct_suffixes() {
        // "a b" and "a_b" both sanitize to "a_b"; without disambiguation one
        // schema's file would overwrite the other's.
        let files = generate_documentation(
            &two_schema_large_snapshot("a b", "a_b"),
            "Big",
            "docs",
            "md",
        );
        let suffixes: Vec<&str> = files[1..].iter().map(|f| f.suffix.as_str()).collect();
        assert_eq!(suffixes.len(), 2);
        assert_ne!(suffixes[0], suffixes[1], "suffixes must not collide");
        // And the index links to both distinct filenames.
        for suffix in suffixes {
            assert!(files[0].content.contains(&format!("docs{suffix}.md")));
        }
    }

    #[test]
    fn filename_segments_are_sanitized() {
        assert_eq!(filename_segment("dbo"), "dbo");
        assert_eq!(filename_segment("my schema!"), "my_schema");
        assert_eq!(filename_segment(""), "default");
        assert_eq!(filename_segment("../etc"), "etc");
    }
}
